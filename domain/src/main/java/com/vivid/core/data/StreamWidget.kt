/** Only the active placement can enable a shared definition. */
fun StreamWidget.settings(base: AppSettings, visible: Boolean): AppSettings = configuration.applyTo(base).copy(
    widgetEnabled = visible && type == WidgetType.TEXT,
    imageWidgetEnabled = visible && type == WidgetType.IMAGE,
    slideshowWidgetEnabled = visible && type == WidgetType.SLIDESHOW,
    qrCodeWidgetEnabled = visible && type == WidgetType.QR_CODE,
    chatOverlayEnabled = visible && type == WidgetType.CHAT,
    gridOverlayEnabled = visible && type == WidgetType.GRID,
    batteryEnabled = visible && type == WidgetType.BATTERY,
    subtitlesEnabled = visible && type == WidgetType.SUBTITLES,
    pomodoroEnabled = visible && type == WidgetType.POMODORO,
)

fun isBrowserWidgetUrl(url: String): Boolean = runCatching {
    val uri = java.net.URI(url)
    uri.scheme.equals("https", ignoreCase = true) && !uri.host.isNullOrBlank()
}.getOrDefault(false)
