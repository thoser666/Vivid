package com.vivid.core.data

import kotlinx.serialization.Serializable

@Serializable
enum class WidgetType { TEXT, BROWSER, IMAGE, SLIDESHOW, QR_CODE, CHAT, GRID, BATTERY, SUBTITLES, POMODORO }

/** Shared content. Placement and visibility in a scene live in SceneWidget. */
@Serializable
data class StreamWidget(
    val id: String,
    val name: String,
    val type: WidgetType,
    val enabled: Boolean = true,
    val configuration: WidgetConfiguration = WidgetConfiguration(),
)

@Serializable
data class SceneWidget(
    val widgetId: String,
    val enabled: Boolean = true,
    val x: Float = 0f,
    val y: Float = 0f,
    val scale: Float = 1f,
) {
    fun normalized() = copy(x = x.coerceIn(0f, 100f), y = y.coerceIn(0f, 100f), scale = scale.coerceIn(0.1f, 4f))
}

